# P2 lane, TDD pair G (governance): the REAL kernel status channel and the
# countable retry witness.
#
# The forensics base (/tmp/perf1lane/forensics-dossier.md section 7.6) found
# the bridge reading the kernel exit status ONLY from the "status" attribute
# of the exec result -- an attribute the real system2 never sets on unix.
# The bake-death #7 precedent (bench/m7/tests/test_p6_mini_fixture.py)
# shows what that means in practice: a kernel that dies after writing
# parsable residue is consumed as a success. The five-gate ledger's
# silent-death/silent-retry mechanism hypothesis for the 20-cell comp_*
# 2x-inflation cluster is the second half of the same blindness.
#
# This file is the RED half of pair G. Unit G1 (hazard characterization)
# passes before and after the fix -- it is the banked proof that the
# attribute-only extraction misclassifies a REAL death whose residue
# parses clean. Units G2-G5 bind the future consumer surface
# (msuiter:::kp_status / kp_exec / kp_run_batch) and are red by absence
# until the GREEN commit lands R/kernel-pipeline.R.
#
# D3: every numeric is generated by .kpp_fixture_v from a set seed; the
# batch face runs on synthetic grids only.

test_that("G1 hazard characterization: attribute-only status reads a real
           batch death with parsable residue as success", {
  sc <- .kpp_death_scenario()
  # The death is real: the exit-status VALUE says 2 (the structured
  # 'error:' line on the kernel's stderr is pinned by the Rust integration
  # suite and by the container witnesses; real-capture text is not a
  # portable property on every R build -- see the helper header).
  expect_identical(sc$rc, 2L)
  # The residue of the valid row 1 parses clean -- that is what makes the
  # silent-consumer hazard real rather than hypothetical.
  expect_true(.kpp_parses_clean(sc$good.out, sc$m, sc$n, sc$k, sc$iters))
  # The exact object the production seam hands upward: sigminer's
  # .kernel_exec captures stdout/stderr to FILES and returns the system2
  # result of that call -- the status VALUE, carrying NO status attribute
  # (the attribute exists only on the TRUE-mode capture shape, which G3(d)
  # rejects outright at the consumer).
  out.f <- tempfile("kpp-legacy-out-")
  err.f <- tempfile("kpp-legacy-err-")
  res <- suppressWarnings(system2(
    sc$bin, .kpp_batch_argv(sc$manifest, sc$in.root, sc$out.root),
    stdout = out.f, stderr = err.f))
  expect_null(attr(res, "status"))
  expect_identical(.kpp_naive_status(res), 0L)           # the misclassifies
  expect_identical(suppressWarnings(as.integer(res)), 2L) # the truth
})

test_that("G2 status channel: a batch death with parsable residue fails
           closed at the consumer", {
  kp.run.batch <- .kpp_surface("kp_run_batch")   # red by absence
  sc <- .kpp_death_scenario()
  # The batch invocation is the REAL certified binary on the REAL value
  # channel (G1 already fixed its status-2 death at 0L of attributes);
  # only the handshake text is seam-served, because this host's build
  # drops system2 capture text in every mode (probe banked at
  # /tmp/perf2lane/logs/system2_modes_probe.txt) and the campaign
  # platforms deliver it verbatim.
  err <- NULL
  .kpp_with_exec(.kpp_mock(function(bin, args) {
    out.f <- tempfile("kpp-death-out-")
    err.f <- tempfile("kpp-death-err-")
    res <- suppressWarnings(system2(bin, args, stdout = out.f,
                                    stderr = err.f))
    attr(res, "stdout") <- if (file.exists(out.f))
      readLines(out.f, warn = FALSE) else character()
    attr(res, "stderr") <- if (file.exists(err.f))
      readLines(err.f, warn = FALSE) else character()
    res
  }), {
    err <- tryCatch({
      kp.run.batch(bin = sc$bin, manifest = sc$manifest, root = sc$in.root,
                   out.root = sc$out.root)
      NULL
    }, error = function(e) conditionMessage(e))
  })
  expect_false(is.null(err), "the death must never be consumed silently")
  expect_true(grepl("exited with status 2", err, fixed = TRUE),
              info = err)  # the exit code itself must be named in the fault
})

test_that("G3 status channel: the status VALUE is the source; attributes
           may only corroborate or falsify", {
  kp.run.batch <- .kpp_surface("kp_run_batch")   # red by absence
  sc <- .kpp_valid_scenario()
  # (a) A real-style death: scalar status 7, no attribute anywhere.
  err <- NULL
  .kpp_with_exec(.kpp_mock(function(bin, args) {
    res <- 7L
    attr(res, "stdout") <- character()
    attr(res, "stderr") <- "error: simulated kernel death"
    res
  }), {
    err <- tryCatch({
      kp.run.batch(bin = sc$bin, manifest = sc$manifest, root = sc$in.root,
                   out.root = sc$out.root)
      NULL
    }, error = function(e) conditionMessage(e))
  })
  expect_false(is.null(err), "scalar status 7 must stop the consumer")
  expect_true(grepl("exited with status 7", err, fixed = TRUE), info = err)
  # The seam-carried stderr witness must be quoted onward into the fault
  # (mock-supplied so the assertion is deterministic on every R build).
  expect_true(grepl("error: simulated kernel death", err, fixed = TRUE),
              info = err)
  # (b) Integrity: a value/attribute disagreement is itself fail-closed --
  # an attribute may falsify the value, never silently overrule it.
  err2 <- NULL
  .kpp_with_exec(.kpp_mock(function(bin, args) {
    res <- 0L
    attr(res, "status") <- 3L
    res
  }), {
    err2 <- tryCatch({
      kp.run.batch(bin = sc$bin, manifest = sc$manifest, root = sc$in.root,
                   out.root = sc$out.root)
      NULL
    }, error = function(e) conditionMessage(e))
  })
  expect_false(is.null(err2), "a status disagreement must not pass")
  expect_true(grepl("status disagreement", err2, fixed = TRUE), info = err2)
  # (c) Status 0 with no residue is a RECEIPT failure, not a status
  # success: consumption is attested per case, so the fault must name the
  # missing case output rather than read as "the kernel said ok".
  err3 <- NULL
  .kpp_with_exec(.kpp_mock(function(bin, args) {
    res <- 0L
    attr(res, "stdout") <- character()
    attr(res, "stderr") <- character()
    res
  }), {
    err3 <- tryCatch({
      kp.run.batch(bin = sc$bin, manifest = sc$manifest, root = sc$in.root,
                   out.root = sc$out.root)
      NULL
    }, error = function(e) conditionMessage(e))
  })
  expect_false(is.null(err3), "un-attested residue must stop consumption")
  expect_true(grepl(sc$case, err3, fixed = TRUE), info = err3)
  # (d) An attribute-only result (no usable value) is the TRUE-mode capture
  # shape arriving at the consumer: fail-closed -- the status must arrive
  # BY VALUE, an attribute alone is never a source.
  err4 <- NULL
  .kpp_with_exec(.kpp_mock(function(bin, args) {
    res <- ""
    attr(res, "status") <- 9L
    res
  }), {
    err4 <- tryCatch({
      kp.run.batch(bin = sc$bin, manifest = sc$manifest, root = sc$in.root,
                   out.root = sc$out.root)
      NULL
    }, error = function(e) conditionMessage(e))
  })
  expect_false(is.null(err4), "attribute-only status must be rejected")
  expect_true(grepl("by value", err4, fixed = TRUE), info = err4)
})

test_that("G4 retry visibility: every re-attempt leaves a countable witness
           and the default route retries never", {
  kp.run.batch <- .kpp_surface("kp_run_batch")   # red by absence
  sc <- .kpp_valid_scenario()
  # A flaky kernel: the first attempt dies (status 2) with no residue;
  # later attempts run for real. The mock delegates through the real
  # system2 VALUE channel -- it never fabricates an attribute.
  st <- new.env(parent = emptyenv())
  st$calls <- 0L
  .kpp_with_exec(.kpp_mock(function(bin, args) {
    st$calls <- st$calls + 1L
    if (st$calls < 2L) {
      res <- 2L
      attr(res, "stderr") <- "error: simulated transient death"
      return(res)
    }
    out.f <- tempfile("kpp-flaky-out-")
    err.f <- tempfile("kpp-flaky-err-")
    res <- suppressWarnings(system2(bin, args, stdout = out.f,
                                    stderr = err.f))
    attr(res, "stdout") <- if (file.exists(out.f))
      readLines(out.f, warn = FALSE) else character()
    attr(res, "stderr") <- if (file.exists(err.f))
      readLines(err.f, warn = FALSE) else character()
    res
  }), {
    # (a) Default route (max_attempts = 1L): the death stops everything,
    # the message counts the attempt, and NO second call ever happens --
    # silent retry is structurally impossible on the default route.
    err <- tryCatch({
      kp.run.batch(bin = sc$bin, manifest = sc$manifest, root = sc$in.root,
                   out.root = sc$out.root)
      NULL
    }, error = function(e) conditionMessage(e))
    expect_false(is.null(err))
    expect_true(grepl("attempt 1", err, fixed = TRUE), info = err)
    expect_identical(st$calls, 1L)  # the no-retry pin
    # (b) Opt-in bounded retry WITH the witness: two attempts are visible
    # in the ledger, one row per attempt, countable from disk. (Fresh
    # scenario: the first block's death already consumed attempt one of
    # the flaky schedule, so the counter restarts here.)
    st$calls <- 0L
    ledger <- tempfile("kpp-ledger-")
    ok <- tryCatch({
      kp.run.batch(bin = sc$bin, manifest = sc$manifest, root = sc$in.root,
                   out.root = sc$out.root, max_attempts = 2L,
                   ledger = ledger, unit = sc$case)
      TRUE
    }, error = function(e) conditionMessage(e))
    expect_identical(ok, TRUE)
    expect_identical(st$calls, 2L)
    rows <- readLines(ledger, warn = FALSE)
    rows <- rows[nzchar(rows)]
    expect_identical(rows[[1L]], "unit,attempt,status,cause")
    data <- rows[-1L]
    expect_identical(length(data), 2L)
    f1 <- strsplit(data[[1L]], ",", fixed = TRUE)[[1L]]
    f2 <- strsplit(data[[2L]], ",", fixed = TRUE)[[1L]]
    expect_identical(f1[1L], sc$case)
    expect_identical(f2[1L], sc$case)
    expect_identical(f1[2L], "1")
    expect_identical(f2[2L], "2")
    expect_identical(f1[3L], "2")   # attempt 1 died with status 2
    expect_identical(f2[3L], "0")   # attempt 2 succeeded
  })
})

test_that("G5 retry is bounded and opt-in: out-of-range budgets are refused
           before any process is spawned", {
  kp.run.batch <- .kpp_surface("kp_run_batch")   # red by absence
  sc <- .kpp_valid_scenario()
  for (bad in list(0L, 5L, 100L, -1L)) {
    err <- tryCatch({
      kp.run.batch(bin = sc$bin, manifest = sc$manifest, root = sc$in.root,
                   out.root = sc$out.root, max_attempts = bad)
      NULL
    }, error = function(e) conditionMessage(e))
    expect_false(is.null(err), paste0("max_attempts=", bad, " must be refused"))
    expect_true(grepl("max_attempts", err, fixed = TRUE), info = err)
  }
})
