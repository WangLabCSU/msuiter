class SyntheticProvider:
    """The deterministic synthetic signatures (the default development/test tier).

    The construction (all determined by the rng of derive_seed("synthetic", seed); the formulas are frozen in
    this docstring):

      flat_a   ~ Dirichlet(1,...,1)                       # the flat signature A
      flat_b   = normalize(0.97*flat_a + 0.03*e)          # the near-duplicate flat pair B
               e ~ Dirichlet(1,...,1)
      clock    = boost(Dirichlet(0.2,...,0.2), subtype=C>T, ×15)   # the clock-type spike
      apo_1    = boost(Dirichlet(0.2,...,0.2), T[C>T], ×40)
      apo_2    = boost(Dirichlet(0.2,...,0.2), T[C>G], ×40)        # the APOBEC pair

      boost(m, mask, k) = normalize(m * (1 + (k-1)*mask))

    The composition-axis extension slots (the functional analogues, the values non-COSMIC; determined by the same rng order):

      smoke4   = boost(Dir(0.2), C>A all channels, ×25)          # the tobacco SBS4 class (C>A dominant)
      uv7      = boost(Dir(0.2), C[C>T]/C[T>C] the dipyrimidine, ×25)  # the UV SBS7 class (the dipyrimidine C>T)
      mmr_common = boost(Dir(0.2), C>A ∪ C>T all channels, ×8)
      SBS6/15/20/21/26/44 = normalize(0.85·mmr_common + 0.15·Dir(0.5)_i)
                  # the MMR correlative group: the near-duplicate family of a shared principal component + independent noise
      pole_common = boost(Dir(0.2), the T background C>A ∪ C>T, ×12)
      SBS10a/b/c/d/28    = normalize(0.85·pole_common + 0.15·Dir(0.5)_i)
                  # the POLE group: same as above (the coarse-grained analogue of the exonuclease-deficiency characteristic channels)

    The catalogue = the 5 truth slots + K_EXTRA "absent" signatures (absent ~ Dirichlet(0.5),
    used for the presence LRT's size calibration (the H0 signatures)) + the composition-axis extension slots.
    """

    K_EXTRA = 5

    def __init__(self, seed: int = 0):
        from .seeds import derive_seed

        rng = np.random.default_rng(derive_seed("synthetic", int(seed)))
        n = 96

        def boost(base, mask, k):
            return _normalize(base * (1.0 + (k - 1) * mask))

        # the channel masks
        subtype = np.arange(n) % 24 // 4
        ref = np.arange(n) // 24
        flank3 = np.arange(n) % 4
        m_ct = (subtype == 2).astype(float)                    # C>T (any ref)
        m_apobec_ct = ((subtype == 2) & (ref == 3)).astype(float)   # T[C>T]
        m_apobec_cg = ((subtype == 1) & (ref == 3)).astype(float)   # T[C>G]

        flat_a = rng.dirichlet(np.ones(n))
        flat_b = _normalize(0.97 * flat_a + 0.03 * rng.dirichlet(np.ones(n)))
        clock = boost(rng.dirichlet(np.full(n, 0.2)), m_ct, 15)
        apo1 = boost(rng.dirichlet(np.full(n, 0.2)), m_apobec_ct, 40)
        apo2 = boost(rng.dirichlet(np.full(n, 0.2)), m_apobec_cg, 40)

        self.truth = {
            "SBS1": clock, "SBS2": apo1, "SBS13": apo2,
            "SBS5": flat_a, "SBS40": flat_b,
        }
        self.absent = {f"ABS{i+1}": rng.dirichlet(np.full(n, 0.5))
                       for i in range(self.K_EXTRA)}

        # ---- the composition-axis extension slots (the functional analogues; see the class docstring formulas) ------------
        m_ca = (subtype == 0).astype(float)                    # C>A (any ref)
        m_uv = ((ref == 1) & (subtype == 2)
                & ((flank3 == 1) | (flank3 == 3))).astype(float)  # C[C>T]/C[T…C>T] the dipyrimidine
        m_mmr = ((subtype == 0) | (subtype == 2)).astype(float)   # C>A ∪ C>T
        m_pole = ((ref == 3) & ((subtype == 0) | (subtype == 2))).astype(float)

        def family_like(mask, k, members, common_weight=0.85):
            common = boost(rng.dirichlet(np.full(n, 0.2)), mask, k)
            return {m: _normalize(common_weight * common
                                  + (1.0 - common_weight) * rng.dirichlet(np.full(n, 0.5)))
                    for m in members}

        extended = {
            "SBS4": boost(rng.dirichlet(np.full(n, 0.2)), m_ca, 25),
            "SBS7": boost(rng.dirichlet(np.full(n, 0.2)), m_uv, 25),
        }
        extended.update(family_like(m_mmr, 8,
                                    ("SBS6", "SBS15", "SBS20", "SBS21",
                                     "SBS26", "SBS44")))
        extended.update(family_like(m_pole, 12,
                                    ("SBS10a", "SBS10b", "SBS10c", "SBS10d",
                                     "SBS28")))
        self.extended = extended

        self.catalog = dict(self.truth)
        self.catalog.update(self.absent)
        self.catalog.update(self.extended)
        self.channel_labels = load_sbs96_labels()

    def signature(self, name: str) -> np.ndarray:
        """Gets the normalized signature spectrum by name (for the truth-composition assembly).

        The v3.6 split-name resolution: a directly stored name wins; only when the catalogue lacks it are the parts merged with equal weights
        (SBS40 → SBS40a+40b+40c, SBS17 → SBS17a/b; the PI derivation ruling)."""
        if name not in self.catalog:
            resolved = _resolve_split_name(self.catalog, name)
            if resolved is not None:
                return resolved
        try:
            return self.catalog[name]
        except KeyError:
            raise ProviderError(
                f"synthetic provider has no slot '{name}' "
                f"(composition axis requests an unknown signature)") from None

    def catalog_matrix(self, names=None) -> tuple:
        """(names, W 96×K); the column order of W matches names and every column sums to 1."""
        names = list(self.catalog) if names is None else list(names)
        return names, np.column_stack([self.catalog[k] for k in names])


def _normalize(v: np.ndarray) -> np.ndarray:
    s = v.sum()
    if s <= 0:
        raise ProviderError("cannot normalize non-positive vector")
    return v / s


def _resolve_split_name(catalog: dict, name: str):
    """Split-name resolution for the frozen truth slots: SBS40 ->
    SBS40a (+SBS40b/c) and SBS17 -> SBS17a/b, equally weighted when
    the unsplit name is absent (v3.6 naming, PI derivation).

    Shared by both providers (2026-10-07 fix: the resolver lived only on
    CosmicFileProvider, so SyntheticProvider.signature crashed on every
    call site). Callers must prefer a direct catalog hit; this resolver
    only supplies the merged substitute for names the catalog lacks.
    """
    # v3.6 split families: SBS7a-d, SBS10a-d, SBS17a-b, SBS40a-c.
    members = sorted(k for k in catalog
                     if k.startswith(name)
                     and len(k) == len(name) + 1
                     and k[len(name)].isalpha())
    if members:
        return sum(catalog[k] for k in members) / len(members)
    return None


