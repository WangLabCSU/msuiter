"""Signature-matrix providers (the licensing red line D3: COSMIC is never checked into the repository).

Two providers:

1. SyntheticProvider (the default): the synthetic signatures generated by Dirichlet; the tests and the development all use this tier.
   The structure deliberately imitates the truth set's functional semantics (the slot labels keep using SBS1/2/13/5/40, but the values
   are not COSMIC signatures): the clock-type spike, the APOBEC-type T[C>T]/T[C>G] dual signatures,
   the near-duplicate flat pair (the synthetic analogue of the P1 mechanism (i) probe). The construction formulas are fully documented and
   fully determined by the seed.
   The extension slots required by the frozen truth composition axis (grid.COMPOSITIONS, adjudication §3 ≥6 groups)
   (the strong signatures SBS4/SBS7, the MMR group SBS6/15/20/21/26/44, the POLE group
   SBS10a/b/c/d/28) are likewise **functional analogues** (the values are non-COSMIC): the strong signatures are boosted
   per their literature-dominant channels; the MMR/POLE groups are constructed as near-duplicate families of
   "a shared principal component + independent Dirichlet noise" (the identifiability pressure of the correlative group being whole-group co-truthful is the measured object). The real
   values are supplied at the formal execution by the cosmic-file provider (the COSMIC v3.6 full 101 signatures).

2. CosmicFileProvider: reads the signature-matrix CSV the user obtained by themselves from the
   environment variable G0_SIGNATURES_PATH (the data acquisition and the license acceptance are the user's action; the harness only validates the format).
   On load it hard-validates against the canonical label order of tools/channel-reference/SBS96.txt:
   the channel-axis label sequence must equal the canonical order item by item (order-sensitive), or the load is rejected.
   This follows the same logic as the conservative posture of tools/channel-reference.

This module contains, embeds or derives no COSMIC value whatsoever.

The PI adjudication addendum (2026-10-06, resolving the "user-supplied file" ambiguity): the cosmic-file's
input files are allowed to be locally derived from the **COSMIC v3.6 reference already bundled in the repository** (refdb v1,
inst/reference/refdb/COSMIC_v3.6/, the sha256 pin ff61b0f, the BSD-2 license, the licensing and provenance governance
inside the A13/refdb governance chain) — the derivation script
tools/g0-derive-inputs.R writes the two files into bench/g0/cache/ (already covered by the gitignore);
the file bodies are never checked into the repository; the D3 red line holds ("not checked in", not "do not exist").
The signature-name mapping record: SBS17a→SBS17, SBS40a→SBS40 (the v3.6 split names merged into the
TRUTH_NAMES slots).
"""

from __future__ import annotations

import csv
import os
from pathlib import Path

import numpy as np

TRUTH_NAMES = ("SBS1", "SBS2", "SBS13", "SBS5", "SBS40")

_REPO_ROOT = Path(__file__).resolve().parents[3]
SBS96_REF_PATH = _REPO_ROOT / "tools" / "channel-reference" / "SBS96.txt"

# The channel-indexing mathematics (bound to the order of SBS96.txt; validated on load):
#   ref     = i // 24          (A, C, G, T)
#   subtype = (i % 24) // 4    (C>A, C>G, C>T, T>A, T>C, T>G)
#   flank3  = i % 4            (A, C, G, T)


def load_sbs96_labels(path: Path = SBS96_REF_PATH) -> tuple:
    """Reads the channel-label canonical order (the order anchor of the simulator's output vectors)."""
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    labels = tuple(ln.strip() for ln in lines if ln.strip())
    if len(labels) != 96:
        raise ValueError(f"SBS96 reference must have 96 labels, got {len(labels)}")
    return labels


class ProviderError(RuntimeError):
    pass


